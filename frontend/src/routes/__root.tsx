import { Toaster } from "sonner";
import { useAuth } from "../lib/auth";

function ThemeContainer({ children }: { children: ReactNode }) {
  const { session } = useAuth();
  
  const primaryColor = session?.branding?.primaryColor || "hsl(221 83% 53%)";
  const accentColor = session?.branding?.accentColor || "hsl(210 30% 94%)";
  
  const themeStyles = {
    "--primary": primaryColor,
    "--ring": primaryColor,
    "--accent": accentColor,
  } as React.CSSProperties;

  return (
    <div style={themeStyles} className="relative z-10 min-h-screen">
      {children}
    </div>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const pathname = router.state.location.pathname;

  useEffect(() => {
    if ("serviceWorker" in navigator) {
      window.addEventListener("load", () => {
        navigator.serviceWorker
          .register("/sw.js")
          .then(
            (reg) => console.log("🔥 [PWA Service Worker] Registered scope:", reg.scope),
            (err) => console.error("❌ [PWA Service Worker] Registration failed:", err)
          );
      });
    }
  }, []);

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <ThemeContainer>
          <div key={pathname} className="route-transition w-full flex flex-col flex-1">
            <Outlet />
          </div>
          <Toaster position="top-right" closeButton richColors />
        </ThemeContainer>
      </AuthProvider>
    </QueryClientProvider>
  );
}
